// Runs the checker on fixtures/check-fixtures.json and reports detections, misses and
// false positives. `node scripts/run-fixtures.mjs --write` also rewrites docs/FIXTURES.md.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { checkText, STATUS } from "../public/iris-rules.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sheet = JSON.parse(readFileSync(join(root, "fixtures/check-fixtures.json"), "utf8"));

export function runFixtures(cases = sheet.cases) {
  const rows = cases.map((c) => {
    const r = checkText(c.text);
    const flagged = r.status !== STATUS.UNKNOWN;
    let outcome = "reported";
    if (c.kind === "scam") outcome = flagged ? "detected" : "missed";
    if (c.kind === "normal") outcome = flagged ? "false positive" : "correct";
    return { ...c, status: r.status, matched: r.findings.map((f) => f.rule ?? f.reason), outcome };
  });
  const count = (kind, outcome) => rows.filter((r) => r.kind === kind && r.outcome === outcome).length;
  return {
    rows,
    summary: {
      scam: rows.filter((r) => r.kind === "scam").length,
      detected: count("scam", "detected"),
      missed: count("scam", "missed"),
      normal: rows.filter((r) => r.kind === "normal").length,
      falsePositives: count("normal", "false positive"),
      uncertain: rows.filter((r) => r.kind === "uncertain").length,
    },
  };
}

export function renderMarkdown({ rows, summary }) {
  const esc = (s) => String(s).replaceAll("|", "\\|");
  const table = (kind) =>
    rows
      .filter((r) => r.kind === kind)
      .map((r) => `| ${r.id} | ${esc(r.text)} | ${r.status} | ${r.matched.join(", ") || "none"} | ${r.outcome} |`)
      .join("\n");
  const head = "| ID | Text | Status | Matched | Outcome |\n| --- | --- | --- | --- | --- |";
  return `# Checker fixture results

Generated by \`npm run fixtures\` from \`fixtures/check-fixtures.json\` (written ${sheet.written}).
All messages are synthetic, written for this sheet. Do not edit this file by hand; \`npm test\` fails if it is out of date.

Statuses: **known-malicious** (exact host on the reported list), **suspicious** (a message pattern or a link pattern matched), **unknown** (nothing matched; not a clearance). There is no "safe" status.

## Summary

| | Count |
| --- | --- |
| Scam cases | ${summary.scam} |
| Detected (suspicious or known-malicious) | ${summary.detected} |
| Missed (returned unknown) | ${summary.missed} |
| Normal / advice cases | ${summary.normal} |
| False positives (normal case flagged) | ${summary.falsePositives} |
| Uncertain cases (reported, not scored) | ${summary.uncertain} |

## Scam

${head}
${table("scam")}

## Normal and advice

${head}
${table("normal")}

## Uncertain

${head}
${table("uncertain")}

## Limits

- 25 hand-written cases are a smoke test, not an accuracy measurement. They were written before the first run and not changed to fit the results.
- Rules match English wording only. Other languages, images and voice notes return unknown.
- The reported-host list is short and dated. Most new phishing hosts are not on it, so a new host usually gets suspicious (from its shape) or unknown, never known-malicious.
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const result = runFixtures();
  const s = result.summary;
  console.log(`scam: ${s.detected}/${s.scam} detected, ${s.missed} missed`);
  console.log(`normal/advice: ${s.falsePositives}/${s.normal} false positives`);
  console.log(`uncertain: ${s.uncertain} reported`);
  for (const r of result.rows) if (r.outcome === "missed" || r.outcome === "false positive") console.log(`  ${r.outcome}: ${r.id} ${r.text}`);
  if (process.argv.includes("--write")) {
    writeFileSync(join(root, "docs/FIXTURES.md"), renderMarkdown(result));
    console.log("wrote docs/FIXTURES.md");
  }
}
